/**
 * Why does this file exist? It is the native build step: it compiles the two Rust crates under native/ for
 * wasm32-unknown-unknown (no bindgen: a plain C ABI over linear memory) and writes each module into the source tree
 * as a generated TypeScript file carrying the bytes as base64, their length and their SHA-256:
 *   native/routing        → src/06_Make_Decisions/routing.wasm.ts   (the track arithmetic of tracks.ts)
 *   native/kv-pager-wasm  → src/09_Cognition/kvPager.wasm.ts        (kv-pager's page table)
 * The generated files are committed: the single-file build (vite) needs no cargo, and the modules are plain
 * strings the bundler inlines like any other source. Run it after a change to a crate (`npm run native:wasm`); the
 * tests (`npm run native:test`, routingWasm.test.ts, prefixCache.test.ts) prove the module in the tree against the
 * TypeScript reference and its own hash, and tools/verify/fvps.sh proves a rebuild gives the committed bytes.
 * What breaks if it is removed? A change to a crate never reaches the page; the committed modules go stale silently.
 */
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { HEADERS } from '../license/headers.mjs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const TARGET = 'wasm32-unknown-unknown'
/**
 * The build is reproducible on any machine: a panic location names its source file, and a path dependency
 * (kv-pager-wasm's ../kv-pager) is named by its absolute path, so without this every checkout would bake its own
 * directory into the module (and ship it). Both crates are built with the checkout mapped to one fixed prefix;
 * tools/verify/fvps.sh rebuilds with the same flag and holds the bytes equal to the committed ones.
 */
export const REMAP = '/crimson-noir'
export const RUSTFLAGS = `--remap-path-prefix=${ROOT}=${REMAP}`

/** Each crate, the wasm file cargo writes for it, and the module it becomes (the constant prefix names its exports). */
const MODULES = [
  {
    crate: 'native/routing', wasm: 'routing.wasm', out: 'src/06_Make_Decisions/routing.wasm.ts', prefix: 'ROUTING_WASM',
    role: 'the fixed track network\'s arc-length arithmetic (native/routing, the WebAssembly core routingWasm.ts loads; tracks.ts stays the reference)',
    breaks: 'routingWasm.ts has no module to instantiate: the fleet runs the TypeScript reference alone',
  },
  {
    crate: 'native/kv-pager-wasm', wasm: 'kv_pager_wasm.wasm', out: 'src/09_Cognition/kvPager.wasm.ts', prefix: 'KV_PAGER_WASM',
    role: 'kv-pager\'s page table behind a C ABI (native/kv-pager-wasm), the prompt-prefix page table prefixCache.ts asks',
    breaks: 'prefixCache.ts has no table: the router\'s ask status has no cache line',
  },
]

/** Brand names compliance.test.ts scrubs: a base64 string could spell one by chance at a +, / or string boundary. */
const SCRUBBED = [/\bxbox\b/i, /\bnintendo\b/i, /\bjoy-?cons?\b/i, /\bthe matrix\b/i, /\bdigital rain\b/i]

for (const m of MODULES) {
  const manifest = join(ROOT, m.crate, 'Cargo.toml')
  execFileSync('cargo', ['build', '--release', '--target', TARGET, '--manifest-path', manifest], { stdio: 'inherit', env: { ...process.env, RUSTFLAGS } })
  const bytes = readFileSync(join(ROOT, m.crate, 'target', TARGET, 'release', m.wasm))
  const base64 = bytes.toString('base64')
  const sha256 = createHash('sha256').update(bytes).digest('hex')
  for (const re of SCRUBBED) {
    if (re.test(base64)) throw new Error(`${m.out}: the base64 text spells "${base64.match(re)[0]}" by chance; change the crate (a comment moves nothing: reorder a function) and rebuild`)
  }
  const text = `${HEADERS.proprietary.map((l) => `// ${l}`).join('\n')}
/**
 * Why does this file exist? It is ${m.role}, compiled to WebAssembly
 * and carried here as base64 so the single-file build needs no cargo and no loader: ${bytes.length} bytes, SHA-256
 * ${sha256}.
 * GENERATED by tools/native/build-wasm.mjs (npm run native:wasm) from ${m.crate}; do not edit by hand.
 * What breaks if it is removed? ${m.breaks}.
 */
export const ${m.prefix}_BYTES = ${bytes.length}
export const ${m.prefix}_SHA256 = '${sha256}'
export const ${m.prefix}_BASE64 =
  '${base64}'
`
  writeFileSync(join(ROOT, m.out), text)
  console.log(`${relative(ROOT, m.out)}: ${bytes.length} wasm bytes, ${text.length} chars, sha256 ${sha256.slice(0, 16)}…`)
}
